package dev.oqthara.stdlib;

import com.code_intelligence.jazzer.api.FuzzedDataProvider;
import com.code_intelligence.jazzer.junit.FuzzTest;
import dev.oqthara.core.Interpreter;
import dev.oqthara.runtime.OqError;
import dev.oqthara.runtime.Span;
import dev.oqthara.runtime.OqCallable;

import java.io.BufferedReader;
import java.io.OutputStream;
import java.io.PrintStream;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Fuzzes the compression builtins: raw DEFLATE ({@code zlib_*}), gzip and zip.
 *
 * <p>These were the two names R-018 still listed as reachable and unfuzzed, together with
 * {@code zip}. They are the most security-relevant builtins the language has, because
 * {@link Compression} does not delegate gzip and zip framing to the JDK: both headers are parsed
 * by hand so a trailing member can be refused instead of silently joined. Hand-written length,
 * offset and flag arithmetic over attacker-supplied bytes is exactly what a fuzzer is for, and
 * the 45 unit tests in {@code CompressionTest} cannot cover it because they supply the inputs a
 * person thought of.
 *
 * <p>The property beyond "no unexpected exception" is that the cap is a cap on <em>work</em>, not
 * on a number the input declares. {@link Compression#MAX_OUTPUT_BYTES} is checked inside the
 * inflate loop after each chunk, so an input claiming to be small while expanding enormously has
 * to be refused rather than allocated. A builtin that reported the cap from a length field would
 * pass every hand-written test and fail here.
 */
class CompressionFuzzTest {
    /** Small enough that the fuzzer explores structure rather than spending its budget on copy. */
    private static final int MAX_HEX = 4096;

    private static final Interpreter INTERPRETER = createInterpreter();

    /**
     * Arbitrary hex into every decompressor.
     *
     * <p>A well-formed refusal is an {@code OqError}; anything else is a defect. This is the
     * target that exercises the headers: a fuzzer-generated byte string reaches the gzip flag
     * bits and the zip central-directory offsets, which are the two places a hand-written parser
     * can read past its buffer or trust a count it should not.
     */
    @FuzzTest(maxDuration = "30s")
    void decompressorsNeverThrowUnexpectedExceptions(FuzzedDataProvider data) {
        String name = data.pickValue(new String[] {
                "zlib_decompress", "gzip_decompress", "zip_decompress"});
        String hex = randomHex(data);
        Object result;
        try {
            result = call(name, List.of(hex));
        } catch (OqError expected) {
            return;
        } catch (StackOverflowError | OutOfMemoryError e) {
            throw new AssertionError(name + "() exhausted the machine on " + shortHex(hex) + ": " + e, e);
        } catch (RuntimeException e) {
            throw new AssertionError(name + "() crashed on " + shortHex(hex) + ": " + e, e);
        }
        if (!(result instanceof String out)) {
            throw new AssertionError(name + "() returned " + typeName(result)
                    + " instead of hex text for " + shortHex(hex));
        }
        // Every decompressor answers in lowercase hex; a produced value that is not is a defect
        // however well-formed the input was.
        if (!out.equals(out.toLowerCase(java.util.Locale.ROOT))) {
            throw new AssertionError(name + "() returned non-lowercase hex for " + shortHex(hex));
        }
    }

    /**
     * Compress, then decompress, and require the original bytes back.
     *
     * <p>Round-tripping is the property a length or offset error breaks silently. The pair is
     * chosen together so the compressed side is always well-formed, which keeps this target about
     * correctness rather than about refusal; refusals are the first target's job.
     *
     * <p>{@code gzip_compress} takes text and {@code zlib_compress} takes hex, so the two are
     * driven separately rather than through one generic path.
     */
    @FuzzTest(maxDuration = "30s")
    void compressionRoundTripsItsOwnOutput(FuzzedDataProvider data) {
        byte[] bytes = data.consumeBytes(MAX_HEX / 2);
        String hex = HexFormat.of().formatHex(bytes);

        String deflated = (String) call("zlib_compress", List.of(hex));
        String reinflated = (String) call("zlib_decompress", List.of(deflated));
        if (!reinflated.equals(hex)) {
            throw new AssertionError("zlib_compress/decompress did not round-trip "
                    + shortHex(hex) + "; got " + shortHex(reinflated));
        }

        // gzip_compress is text-in, and it re-encodes as UTF-8. Comparing its output against the
        // bytes that went in would be wrong for any input that is not already valid UTF-8, so the
        // text itself is the round-trip identity here.
        String text = data.consumeString(MAX_HEX / 2);
        String gzipped = (String) call("gzip_compress", List.of(text));
        String gunzipped = (String) call("gzip_decompress", List.of(gzipped));
        String expected = HexFormat.of().formatHex(text.getBytes(StandardCharsets.UTF_8));
        if (!gunzipped.equals(expected)) {
            throw new AssertionError("gzip_compress/decompress did not round-trip "
                    + shortHex(expected) + "; got " + shortHex(gunzipped));
        }
    }

    /**
     * A zip of one entry, decompressed, must give that entry's content back.
     *
     * <p>Entry names are fuzzer-chosen but constrained to what the archive format can carry
     * without meaning something else. A name the writer accepts and the reader refuses is the
     * defect this looks for, and it is the one that made traversal names a security fix rather
     * than a tidiness one.
     */
    @FuzzTest(maxDuration = "30s")
    void zipRoundTripsOneEntry(FuzzedDataProvider data) {
        String name = safeEntryName(data);
        String content = HexFormat.of().formatHex(data.consumeBytes(MAX_HEX / 4));
        Map<String, Object> entries = new LinkedHashMap<>();
        entries.put(name, content);
        String archived;
        try {
            archived = (String) call("zip_compress", List.of(entries));
        } catch (OqError refused) {
            return;
        }
        Object unpacked;
        try {
            unpacked = call("zip_decompress", List.of(archived));
        } catch (OqError refused) {
            throw new AssertionError("zip_compress() produced an archive zip_decompress() refuses "
                    + "for entry " + escape(name) + ": " + refused.getMessage(), refused);
        }
        if (!(unpacked instanceof Map<?, ?> out)) {
            throw new AssertionError("zip_decompress() returned " + typeName(unpacked)
                    + " instead of a map for entry " + escape(name));
        }
        if (out.size() != 1) {
            throw new AssertionError("one entry went in and " + out.size() + " came out for "
                    + escape(name));
        }
        Object roundTripped = out.get(name);
        if (!content.equals(roundTripped)) {
            throw new AssertionError("zip round trip changed the content of entry "
                    + escape(name));
        }
    }

    /**
     * Builds a name the archive can hold without the name becoming a claim about the filesystem.
     *
     * <p>The reader refuses absolute names, backslashes and {@code ..} segments, and the writer
     * must refuse the same ones -- that is a deliberate policy, not a bug to report. Producing
     * one of those names would make this target assert a round trip the design forbids, so the
     * characters that could spell one are removed before the name is used.
     */
    private static String safeEntryName(FuzzedDataProvider data) {
        String raw = data.consumeString(48);
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < raw.length() && sb.length() < 32; i++) {
            char c = raw.charAt(i);
            if (c == '/' || c == '\\' || c < 0x20 || c > 0x7E) {
                continue;
            }
            sb.append(c);
        }
        if (sb.length() == 0) {
            sb.append("entry");
        }
        // A leading separator is what "absolute" means here, and '.' alone is not a segment.
        return sb.toString();
    }

    private static String randomHex(FuzzedDataProvider data) {
        int length = data.consumeInt(0, MAX_HEX / 2);
        return HexFormat.of().formatHex(data.consumeBytes(length));
    }

    private static Object call(String name, List<Object> args) {
        OqCallable callable = INTERPRETER.builtins().get(name);
        if (callable == null) throw new AssertionError("stdlib does not define '" + name + "'");
        return callable.call(INTERPRETER, args, Span.synthetic());
    }

    private static String typeName(Object value) {
        if (value == null) return "nothing";
        if (value instanceof List<?>) return "a list";
        if (value instanceof Map<?, ?>) return "a map";
        if (value instanceof String) return "text";
        if (value instanceof Boolean) return "a boolean";
        if (value instanceof Number) return "a number";
        return value.getClass().getSimpleName();
    }

    private static String shortHex(String hex) {
        if (hex == null) return "null";
        return hex.length() > 80 ? hex.substring(0, 80) + "..." : hex;
    }

    private static String escape(String text) {
        StringBuilder sb = new StringBuilder("\"");
        for (int i = 0; i < text.length() && i < 100; i++) {
            char c = text.charAt(i);
            if (c < 0x20 || c > 0x7E || c == '"' || c == '\\') {
                sb.append(String.format("\\u%04X", (int) c));
            } else {
                sb.append(c);
            }
        }
        return sb.append('"').toString();
    }

    private static Interpreter createInterpreter() {
        PrintStream sink = new PrintStream(OutputStream.nullOutputStream(), true,
                StandardCharsets.UTF_8);
        Interpreter interpreter = new Interpreter(sink, sink,
                new BufferedReader(new StringReader("")), List.of(), Path.of("."),
                new MethodResolverImpl());
        Stdlib.install(interpreter);
        return interpreter;
    }
}
