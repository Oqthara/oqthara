package dev.oqthara.runtime;

import java.util.Objects;

public final class OqData {
    private final String typeName;
    private final java.util.LinkedHashMap<String, Object> fields;
    private final boolean immutable;

    public OqData(String typeName, java.util.LinkedHashMap<String, Object> fields) {
        this(typeName, fields, false);
    }

    /**
     * @param immutable a {@code data} type declared with the {@code immutable} modifier: its
     *     fields are fixed at construction and the value is usable as a map key or set member
     *     (ADR-0028). Mutability belongs to the type, so every instance of one declaration
     *     agrees.
     */
    public OqData(String typeName, java.util.LinkedHashMap<String, Object> fields, boolean immutable) {
        this.typeName = Objects.requireNonNull(typeName);
        this.fields = new java.util.LinkedHashMap<>(fields);
        this.immutable = immutable;
    }

    /** Whether this value's fields are fixed at construction. */
    public boolean immutable() {
        return immutable;
    }

    public String typeName() {
        return typeName;
    }

    public java.util.LinkedHashMap<String, Object> fields() {
        return fields;
    }

    public boolean has(String name) {
        return fields.containsKey(name);
    }

    public Object get(String name) {
        return fields.get(name);
    }

    /**
     * Writes a field. Refuses on an immutable declaration: this is the single write path, shared
     * by the interpreter and generated bytecode, so neither backend can forget the rule
     * (ADR-0028). The hint names the repair, because rebuilding the value is not discoverable
     * from the error alone.
     *
     * @throws OqError when this value was constructed from an immutable declaration
     */
    public void set(String name, Object value) {
        set(name, value, Errors.current());
    }

    /** The same write at a caller-supplied position, so the diagnostic points at the assignment. */
    public void set(String name, Object value, Span span) {
        if (immutable) {
            throw new OqError(typeName + " is immutable, so field '" + name + "' cannot be changed",
                    span, rebuildHint(name));
        }
        fields.put(name, value);
    }

    /** The same-type reconstruction a caller should write instead, with every field shown. */
    private String rebuildHint(String changing) {
        StringBuilder hint = new StringBuilder("Build a new value instead: ").append(typeName).append('(');
        boolean first = true;
        for (java.util.Map.Entry<String, Object> field : fields.entrySet()) {
            if (!first) hint.append(", ");
            first = false;
            hint.append(field.getKey()).append(": ");
            if (field.getKey().equals(changing)) {
                hint.append("...");
            } else {
                Object shown = field.getValue();
                hint.append(shown instanceof String text ? "\"" + text + "\"" : Values.repr(shown));
            }
        }
        return hint.append(")").toString();
    }

    /**
     * A {@code data} value equals another of the same type with equal fields, where field
     * equality is {@link Values#equal} so that numbers widen inside an object exactly as they
     * do everywhere else (ADR-0017).
     */
    @Override
    public boolean equals(Object other) {
        if (this == other) return true;
        if (!(other instanceof OqData data)) return false;
        return typeName.equals(data.typeName) && Values.dataFieldsEqual(fields, data.fields);
    }

    @Override
    public int hashCode() {
        return Value.hashing(this);
    }

    @Override
    public String toString() {
        return Values.repr(this);
    }
}
