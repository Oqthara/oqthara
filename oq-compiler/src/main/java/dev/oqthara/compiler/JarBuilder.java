package dev.oqthara.compiler;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.jar.Attributes;
import java.util.jar.JarEntry;
import java.util.jar.JarOutputStream;
import java.util.jar.Manifest;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;

/**
 * Builds an executable jar from a generated program class plus the Oqthara runtime classes
 * that are already on the current classpath. No network, no external dependency, and it
 * works from a plain {@code build/classes} directory as well as from a jar.
 */
public final class JarBuilder {
    private static final String[] PREFIXES = {
            "dev/oqthara/core/",
            "dev/oqthara/runtime/",
            "dev/oqthara/stdlib/",
            "dev/oqthara/cli/EmbeddedMain",
            "dev/oqthara/cli/Modules",
            "dev/oqthara/cli/OqRunner",
            "dev/oqthara/cli/Details",
            // A built jar must be standalone, and the SQLite driver is the first dependency
            // outside dev.oqthara that a program can reach. Without these the jar compiles and
            // then fails at run time with "the SQLite driver is missing from this build".
            "org/sqlite/",
            // sqlite-jdbc logs through SLF4J, so the API and the no-op binding the stdlib adds
            // have to travel with it; the API alone fails with ClassNotFoundException.
            "org/slf4j/",
    };

    private JarBuilder() {
    }

    public record Result(Path jar, int classes, int skipped) {
    }

    public static Result build(Path output, String mainClass, String source, String sourceName) throws IOException {
        return build(output, mainClass, source, sourceName, null);
    }

    /**
     * When {@code compiledClass} is present it is used verbatim and the source is not
     * embedded: the jar contains real generated bytecode, not a script for the interpreter.
     */
    public static Result build(Path output, String mainClass, String source, String sourceName,
                               byte[] compiledClass) throws IOException {
        Path parent = output.toAbsolutePath().getParent();
        if (parent != null) Files.createDirectories(parent);

        Manifest manifest = new Manifest();
        manifest.getMainAttributes().put(Attributes.Name.MANIFEST_VERSION, "1.0");
        manifest.getMainAttributes().put(Attributes.Name.MAIN_CLASS, mainClass);
        manifest.getMainAttributes().putValue("Created-By", "Oqthara oq build");
        manifest.getMainAttributes().putValue("Oqthara-Backend",
                compiledClass == null ? "classfile-launcher" : "classfile-compiled");

        byte[] programBytes = compiledClass != null
                ? compiledClass
                : ClassFileWriter.programClass(mainClass, source);

        Set<String> written = new LinkedHashSet<>();
        int classes;
        int skipped = 0;
        try (OutputStream file = Files.newOutputStream(output);
             JarOutputStream jar = new JarOutputStream(file)) {
            jar.putNextEntry(new JarEntry("META-INF/MANIFEST.MF"));
            manifest.write(jar);
            jar.closeEntry();

            jar.putNextEntry(new JarEntry(mainClass.replace('.', '/') + ".class"));
            jar.write(programBytes);
            jar.closeEntry();
            written.add(mainClass.replace('.', '/') + ".class");

            for (ClassSource classSource : classSources()) {
                skipped += classSource.copyInto(jar, written);
            }
            classes = written.size();

            if (compiledClass == null) {
                jar.putNextEntry(new JarEntry("oq/main.oq"));
                jar.write(source.getBytes(StandardCharsets.UTF_8));
                jar.closeEntry();

                jar.putNextEntry(new JarEntry("oq/source-name.txt"));
                jar.write(sourceName.getBytes(StandardCharsets.UTF_8));
                jar.closeEntry();
            }
        }
        return new Result(output, classes, skipped);
    }

    /** Rejects absolute paths, drive letters and any ".." segment in a jar entry name. */
    public static boolean isSafeEntryName(String entry) {
        if (entry == null || entry.isBlank()) return false;
        if (entry.startsWith("/") || entry.startsWith("\\")) return false;
        if (entry.length() > 1 && entry.charAt(1) == ':') return false;
        String normalized = entry.replace('\\', '/');
        for (String segment : normalized.split("/")) {
            if (segment.equals("..")) return false;
        }
        return true;
    }

    private static boolean wanted(String entry) {
        for (String prefix : PREFIXES) {
            if (entry.startsWith(prefix)) return true;
        }
        return false;
    }

    /**
     * A place classes can be copied from. Sources hand their wanted entries to the builder in
     * one pass: reading a single entry out of a jar means inflating everything before it, so a
     * get-one-at-a-time API would re-inflate the archive once per copied class.
     */
    private interface ClassSource {
        /** Copies every wanted entry not already written; returns how many were skipped. */
        int copyInto(JarOutputStream jar, Set<String> written) throws IOException;
    }

    private static List<ClassSource> classSources() {
        List<ClassSource> sources = new ArrayList<>();
        String classPath = System.getProperty("java.class.path", "");
        for (String element : classPath.split(java.io.File.pathSeparator)) {
            if (element.isBlank()) continue;
            Path path = Path.of(element);
            if (Files.isDirectory(path)) {
                sources.add(directorySource(path));
            } else if (element.endsWith(".jar") && Files.isRegularFile(path)) {
                sources.add(jarSource(path));
            }
        }
        Path ownLocation = locateOwnClasses();
        if (ownLocation != null) {
            if (Files.isDirectory(ownLocation)) {
                sources.add(directorySource(ownLocation));
            } else {
                sources.add(jarSource(ownLocation));
            }
        }
        return sources;
    }

    private static Path locateOwnClasses() {
        try {
            var url = JarBuilder.class.getProtectionDomain().getCodeSource();
            if (url == null) return null;
            return Path.of(url.getLocation().toURI());
        } catch (URISyntaxException | SecurityException e) {
            return null;
        }
    }

    private static ClassSource directorySource(Path root) {
        return (jar, written) -> {
            List<String> entries;
            try (Stream<Path> stream = Files.walk(root)) {
                entries = stream.filter(Files::isRegularFile)
                        .map(p -> root.relativize(p).toString().replace('\\', '/'))
                        .toList();
            }
            int skipped = 0;
            for (String entry : entries) {
                if (!isSafeEntryName(entry)) {
                    skipped++;
                    continue;
                }
                if (!wanted(entry) || written.contains(entry)) continue;
                jar.putNextEntry(new JarEntry(entry));
                jar.write(Files.readAllBytes(root.resolve(entry)));
                jar.closeEntry();
                written.add(entry);
            }
            return skipped;
        };
    }

    /**
     * Copies a jar's wanted entries in a single pass over the archive. The builder shares one
     * {@code written} set across all sources, so the first source to supply an entry wins.
     */
    private static ClassSource jarSource(Path jarPath) {
        return (jar, written) -> {
            try (ZipInputStream zip = new ZipInputStream(Files.newInputStream(jarPath))) {
                ZipEntry entry;
                int skipped = 0;
                while ((entry = zip.getNextEntry()) != null) {
                    if (entry.isDirectory()) continue;
                    String name = entry.getName();
                    if (!isSafeEntryName(name)) {
                        skipped++;
                        continue;
                    }
                    if (!wanted(name) || written.contains(name)) continue;
                    ByteArrayOutputStream buffer = new ByteArrayOutputStream();
                    zip.transferTo(buffer);
                    jar.putNextEntry(new JarEntry(name));
                    jar.write(buffer.toByteArray());
                    jar.closeEntry();
                    written.add(name);
                }
                return skipped;
            }
        };
    }

    static byte[] readAll(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        in.transferTo(out);
        return out.toByteArray();
    }
}
