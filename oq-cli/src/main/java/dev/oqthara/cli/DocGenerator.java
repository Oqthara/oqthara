package dev.oqthara.cli;

import dev.oqthara.core.Ast;
import dev.oqthara.core.Docstring;
import dev.oqthara.core.Lexer;
import dev.oqthara.core.Modules;
import dev.oqthara.core.Parser;
import dev.oqthara.runtime.OqError;

import java.io.File;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * Generates reference documentation from the code that implements the language, so the
 * docs cannot list a function that does not exist. It reads the registration calls in the
 * standard library and the keywords from the lexer.
 */
final class DocGenerator {
    private DocGenerator() {
    }

    static int run(PrintStream out, PrintStream err, String[] args) {
        if (args.length > 0 && args[0].equals("--source")) {
            return runSource(out, err, args);
        }
        Path root = Path.of(args.length > 0 ? args[0] : ".");
        Path stdlib = root.resolve("oq-stdlib/src/main/java/dev/oqthara/stdlib");
        Path methods = stdlib.resolve("MethodResolverImpl.java");
        Path builtins = stdlib.resolve("Stdlib.java");
        if (!Files.exists(builtins) || !Files.exists(methods)) {
            err.println("Cannot find the standard library sources under " + root.toAbsolutePath());
            return 2;
        }
        Path output = root.resolve("docs/stdlib/reference.md");
        try {
            String markdown = generateFrom(stdlib, methods);
            Files.createDirectories(output.getParent());
            Files.writeString(output, markdown, StandardCharsets.UTF_8);
        } catch (Exception e) {
            err.println("Cannot generate documentation: " + e.getMessage());
            return 1;
        }
        out.println("generated " + root.relativize(output));
        return 0;
    }

    /**
     * {@code oq doc --source <path>}: reference pages for the declarations in Oqthara source,
     * read from the docstrings those declarations carry (ADR-0030).
     *
     * <p>A path that is a directory is walked for {@code .oq} files; a file is documented on
     * its own. Output goes to standard output unless {@code --out <file>} is given, because a
     * project's own documentation belongs wherever the project keeps it rather than in a fixed
     * place this command would have to guess.
     */
    static int runSource(PrintStream out, PrintStream err, String[] args) {
        Path source = null;
        Path destination = null;
        for (int i = 1; i < args.length; i++) {
            if (args[i].equals("--out") && i + 1 < args.length) {
                destination = Path.of(args[++i]);
            } else if (source == null) {
                source = Path.of(args[i]);
            } else {
                err.println("oq doc --source takes one path");
                return 2;
            }
        }
        if (source == null) {
            err.println("oq doc --source needs a file or directory");
            return 2;
        }
        if (!Files.exists(source)) {
            err.println("Cannot find " + source);
            return 2;
        }
        try {
            List<Path> files = new ArrayList<>();
            if (Files.isDirectory(source)) {
                try (var walk = Files.walk(source)) {
                    walk.filter(p -> p.toString().endsWith(".oq")).sorted().forEach(files::add);
                }
            } else {
                files.add(source);
            }
            if (files.isEmpty()) {
                err.println("No .oq files under " + source.toAbsolutePath());
                return 2;
            }
            StringBuilder markdown = new StringBuilder("# API reference\n\n");
            markdown.append("> Generated by `oq doc --source`. Do not edit by hand.\n\n");
            markdown.append("Every entry is read from a declaration's documentation comment, so a ")
                    .append("page cannot describe a function the source does not have.\n\n");
            int undocumented = 0;
            int documented = 0;
            // Modules reached only through `use` are documented too, so a page for a project
            // describes the functions its programs can actually call. A module that is also
            // under the walked directory is documented once, in walk order.
            Set<Path> documentedFiles = new LinkedHashSet<>();
            for (Path file : files) documentedFiles.add(file.toAbsolutePath().normalize());
            List<Path> pending = new ArrayList<>(files);
            for (int next = 0; next < pending.size(); next++) {
                Path file = pending.get(next);
                String text = Files.readString(file, StandardCharsets.UTF_8);
                Ast.Program program;
                try {
                    program = Parser.parse(file.getFileName().toString(), text);
                } catch (OqError e) {
                    err.println("Cannot parse " + file + ": " + e.getMessage());
                    return 1;
                }
                List<String> entries = new ArrayList<>();
                for (Ast.Stmt stmt : program.statements()) {
                    String entry = entry(stmt);
                    if (entry != null) {
                        entries.add(entry);
                        if (docOf(stmt) == null) {
                            undocumented++;
                        } else {
                            documented++;
                        }
                    }
                }
                if (!entries.isEmpty()) {
                    markdown.append("## ").append(heading(file, source)).append("\n\n");
                    entries.forEach(e -> markdown.append(e));
                }
                for (Path used : followedModules(program, file, err)) {
                    if (documentedFiles.add(used)) pending.add(used);
                }
            }
            markdown.append("---\n\n")
                    .append(documented).append(" documented, ")
                    .append(undocumented).append(" undocumented.\n");
            if (destination == null) {
                out.print(markdown);
            } else {
                Files.createDirectories(destination.toAbsolutePath().getParent());
                Files.writeString(destination, markdown.toString(), StandardCharsets.UTF_8);
                out.println("generated " + destination);
            }
            return 0;
        } catch (Exception e) {
            err.println("Cannot generate documentation: " + e.getMessage());
            return 1;
        }
    }

    /**
     * The heading for one file: its name when it sits directly under the documented path, and
     * its path from there when a walk reached it in a subdirectory or an import reached it
     * outside. Two modules named {@code util.oq} in different directories would otherwise
     * produce two sections with one name.
     */
    private static String heading(Path file, Path source) {
        Path root = Files.isDirectory(source) ? source.toAbsolutePath().normalize()
                : source.toAbsolutePath().normalize().getParent();
        Path absolute = file.toAbsolutePath().normalize();
        Path shown = root != null && absolute.startsWith(root)
                ? root.relativize(absolute)
                : absolute.getFileName();
        // Relative paths use the host's separator, so without this a page generated on Windows
        // would head a module one way and a page generated on Linux another. A published page
        // must not depend on where it was built.
        return shown.toString().replace(File.separatorChar, '/');
    }

    /**
     * The modules one file imports, resolved through {@link Modules#resolveModule} so that this
     * shares the interpreter's search order rather than describing a different one.
     *
     * <p>An import that does not resolve is reported and skipped: a single missing module in a
     * tree should not suppress the documentation of everything else, and the interpreter would
     * reject the program anyway, so the message is a diagnostic rather than a silent omission.
     */
    private static List<Path> followedModules(Ast.Program program, Path file, PrintStream err) {
        List<Path> resolved = new ArrayList<>();
        Path base = file.toAbsolutePath().normalize().getParent();
        for (Ast.Stmt stmt : program.statements()) {
            if (!(stmt instanceof Ast.ImportStmt importStmt)) continue;
            try {
                resolved.add(Modules.resolveModule(importStmt.path(), base, importStmt.span())
                        .toAbsolutePath().normalize());
            } catch (OqError e) {
                err.println("Skipping module import in " + file.getFileName() + ": "
                        + e.getMessage());
            }
        }
        return resolved;
    }

    private static String docOf(Ast.Stmt stmt) {
        if (stmt instanceof Ast.FuncDecl f) {
            return f.doc();
        }
        if (stmt instanceof Ast.DataDecl d) {
            return d.doc();
        }
        if (stmt instanceof Ast.ClassDecl c) {
            return c.doc();
        }
        if (stmt instanceof Ast.ContractDecl k) {
            return k.doc();
        }
        return null;
    }

    private static String entry(Ast.Stmt stmt) {
        if (stmt instanceof Ast.FuncDecl f) {
            return page("fun " + f.name() + "(" + String.join(", ", f.params()) + ")", f.doc(),
                    f.params());
        }
        if (stmt instanceof Ast.DataDecl d) {
            List<String> fields = d.fields().stream().map(Ast.FieldDef::name).toList();
            return page("data " + d.name() + "(" + String.join(", ", fields) + ")"
                    + (d.immutable() ? " immutable" : ""), d.doc(), fields);
        }
        if (stmt instanceof Ast.ClassDecl c) {
            List<String> fields = c.fields().stream().map(Ast.FieldDef::name).toList();
            return page("class " + c.name() + "(" + String.join(", ", fields) + ")", c.doc(),
                    fields);
        }
        if (stmt instanceof Ast.ContractDecl k) {
            StringBuilder body = new StringBuilder();
            body.append("contract ").append(k.name()).append("\n");
            for (Ast.Signature signature : k.methods()) {
                // A contract records arity, not parameter names, so the placeholders are
                // positional rather than the names the implementing class happens to use.
                String placeholders = java.util.stream.IntStream.rangeClosed(1, signature.arity())
                        .mapToObj(i -> "arg" + i)
                        .collect(java.util.stream.Collectors.joining(", "));
                body.append("  fun ").append(signature.name()).append("(")
                        .append(placeholders).append(")\n");
            }
            return page(body.toString().stripTrailing(), k.doc(), List.of());
        }
        return null;
    }

    private static String page(String heading, String doc, List<String> params) {
        StringBuilder sb = new StringBuilder();
        sb.append("### ").append(heading).append("\n\n");
        if (doc == null) {
            sb.append("_Undocumented._\n\n");
            return sb.toString();
        }
        Docstring parsed = Docstring.parse(doc);
        if (!parsed.summary().isBlank()) {
            sb.append(parsed.summary()).append("\n\n");
        }
        List<String> documented = new ArrayList<>();
        for (String param : params) {
            String text = parsed.param(param);
            if (text != null) {
                documented.add("- `" + param + "` " + text);
            }
        }
        if (!documented.isEmpty()) {
            sb.append("Parameters:\n\n");
            documented.forEach(line -> sb.append(line).append('\n'));
            sb.append('\n');
        }
        appendTag(sb, parsed, "return", "Returns");
        appendTag(sb, parsed, "throws", "Throws");
        appendTag(sb, parsed, "since", "Since");
        appendTag(sb, parsed, "deprecated", "Deprecated");
        appendTag(sb, parsed, "author", "Author");
        appendTag(sb, parsed, "see", "See also");
        for (String name : parsed.tagNames()) {
            if (!Docstring.knownTags().contains(name)) {
                appendTag(sb, parsed, name, "@" + name);
            }
        }
        return sb.toString();
    }

    private static void appendTag(StringBuilder sb, Docstring doc, String tag, String label) {
        String text = doc.tag(tag);
        if (text != null && !text.isBlank()) {
            sb.append(label).append(": ").append(text).append("\n\n");
        }
    }

    /**
     * Scans every {@code *Module.java} in the standard library package, not just
     * {@code Stdlib.java}. Modules live in their own files, and reading only one file would
     * leave their functions out of a page that claims to list every built-in.
     */
    static String generateFrom(Path stdlibDir, Path methodsFile) throws Exception {
        Map<String, List<String>> builtins = new TreeMap<>();
        try (var files = Files.list(stdlibDir)) {
            List<Path> sources = files
                    .filter(p -> p.getFileName().toString().endsWith(".java"))
                    .sorted()
                    .toList();
            for (Path source : sources) {
                builtins.putAll(extract(source, "NativeFunction"));
            }
        }
        return render(builtins, methodsFile);
    }

    private static String render(Map<String, List<String>> builtins, Path methodsFile)
            throws Exception {
        Map<String, List<String>> methods = new LinkedHashMap<>();
        extractMethods(methodsFile, methods);

        StringBuilder sb = new StringBuilder();
        sb.append("# Standard library reference\n\n");
        sb.append("> Generated by `oq doc`. Do not edit by hand.\n\n");
        sb.append("Every entry below is read from the implementation, so this page cannot ")
                .append("list a function that does not exist.\n\n");

        sb.append("## Keywords\n\n");
        List<String> keywords = new ArrayList<>(Lexer.KEYWORDS);
        keywords.sort(String::compareTo);
        sb.append(String.join(", ", keywords.stream().map(k -> "`" + k + "`").toList()));
        sb.append("\n\n").append(keywords.size()).append(" keywords (budget: 30).\n\n");

        sb.append("## Global functions\n\n");
        sb.append("| Function | Source |\n|---|---|\n");
        for (var entry : new TreeMap<>(builtins).entrySet()) {
            sb.append("| `").append(entry.getKey()).append("` | ")
                    .append(String.join(", ", entry.getValue())).append(" |\n");
        }

        sb.append("\n## Methods on values\n\n");
        for (var group : methods.entrySet()) {
            sb.append("### ").append(group.getKey()).append("\n\n");
            sb.append(String.join(", ", group.getValue().stream().map(m -> "`." + m + "()`").toList()));
            sb.append("\n\n");
        }

        sb.append("## Java interoperability\n\n");
        sb.append("`use java.time.LocalDate` imports any class. Constructors, instance methods ")
                .append("and static methods use the same dot syntax as Oqthara values.\n");
        return sb.toString();
    }

    private static Map<String, List<String>> extract(Path file, String marker) throws Exception {
        String source = Files.readString(file);
        Map<String, List<String>> result = new TreeMap<>();
        var pattern = java.util.regex.Pattern.compile(
                marker + "\\.(?:of|variadic)\\(\"([A-Za-z_][A-Za-z0-9_]*)\"");
        var matcher = pattern.matcher(source);
        while (matcher.find()) {
            List<String> sources = result.computeIfAbsent(matcher.group(1), k -> new ArrayList<>());
            if (!sources.contains("built-in")) sources.add("built-in");
        }
        return result;
    }

    /** How many braces are open between {@code open} and {@code at}. */
    private static int braceDepth(String source, int open, int at) {
        int depth = 0;
        for (int i = open; i < at && i < source.length(); i++) {
            char c = source.charAt(i);
            if (c == '{') depth++;
            else if (c == '}') depth--;
        }
        return depth;
    }

    private static void extractMethods(Path file, Map<String, List<String>> into) throws Exception {
        String source = Files.readString(file);
        String current = "general";
        var casePattern = java.util.regex.Pattern.compile(
                "case\\s+((?:\"[a-z_][a-z0-9_]*\"\\s*,?\\s*)+)\\s*->");
        var methodStart = java.util.regex.Pattern.compile(
                "private\\s+OqCallable\\s+(\\w+)\\(\\s*(?:List|Map|Set|String|Object)");
        int lastGroupStart = 0;
        var groupMatcher = java.util.regex.Pattern.compile(
                "private\\s+OqCallable\\s+(\\w+)\\(").matcher(source);
        List<int[]> groups = new ArrayList<>();
        List<String> names = new ArrayList<>();
        while (groupMatcher.find()) {
            groups.add(new int[]{groupMatcher.start()});
            names.add(groupMatcher.group(1));
        }
        for (int g = 0; g < groups.size(); g++) {
            int start = groups.get(g)[0];
            int end = g + 1 < groups.size() ? groups.get(g + 1)[0] : source.length();
            String block = source.substring(start, end);
            current = switch (names.get(g)) {
                case "listMethod" -> "list";
                case "mapMethod" -> "map";
                case "setMethod" -> "set";
                case "frozenSetMethod" -> "frozenset";
                case "textMethod" -> "text";
                case "numberMethod" -> "number";
                case "rangeMethod" -> "range";
                default -> names.get(g);
            };
            // Only arms of the outermost switch count. `rangeMethod` switches again inside a
            // single arm to share one body between sum, sorted and reverse, and counting those
            // inner labels listed each of them twice.
            int switchOpen = block.indexOf("switch (name)");
            int switchBrace = switchOpen < 0 ? -1 : block.indexOf('{', switchOpen);
            var matcher = casePattern.matcher(block);
            List<String> namesInBlock = new ArrayList<>();
            while (matcher.find()) {
                if (switchBrace >= 0 && braceDepth(block, switchBrace, matcher.start()) != 1) continue;
                // A `case "x" -> null` arm refuses the name rather than providing it, so a
                // listing that counted it would promise a method the family does not have.
                String arm = block.substring(matcher.end(), Math.min(block.length(), matcher.end() + 12));
                if (arm.stripLeading().startsWith("null")) continue;
                for (String part : matcher.group(1).split(",")) {
                    String name = part.replace("\"", "").strip();
                    if (!name.isEmpty()) namesInBlock.add(name);
                }
            }
            namesInBlock.sort(String::compareTo);
            into.put(current, namesInBlock);
        }
    }
}
