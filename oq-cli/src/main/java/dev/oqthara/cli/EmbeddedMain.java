package dev.oqthara.cli;

import dev.oqthara.core.Ast;
import dev.oqthara.core.Interpreter;
import dev.oqthara.core.Parser;
import dev.oqthara.runtime.OqError;
import dev.oqthara.stdlib.MethodResolverImpl;
import dev.oqthara.stdlib.Stdlib;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * Entry point for a jar produced by {@code oq build}. It reads the embedded program source
 * and runs it on the interpreter.
 *
 * <p>This is the honest first step of the compiled-jar story: the artifact is a real,
 * self-contained jar with a real class file and a real {@code main}, and the program inside
 * is still interpreted. `docs/spec/backend.md` states that boundary explicitly.
 */
public final class EmbeddedMain {
    /** Arguments of the last {@code main} invocation, kept for the legacy {@code run(String)}. */
    private static volatile String[] programArguments = new String[0];

    private EmbeddedMain() {
    }

    public static void main(String[] args) {
        String source = readResource("oq/main.oq");
        if (source == null) {
            System.err.println("error: this jar does not contain an embedded Oqthara program");
            System.exit(2);
        }
        String sourceName = readResource("oq/source-name.txt");
        if (sourceName == null || sourceName.isBlank()) sourceName = "main.oq";
        programArguments = args == null ? new String[0] : args.clone();
        run(source, sourceName.strip(), programArguments, Path.of("."));
    }

    /** Called from generated bytecode: passes the real program arguments through. */
    public static void runWithArgs(String source, String[] args) {
        String name = readResource("oq/source-name.txt");
        if (name == null || name.isBlank()) name = "main.oq";
        run(source, name.strip(), args == null ? new String[0] : args, Path.of("."));
    }

    /** Kept for older generated jars. */
    public static void run(String source) {
        String name = readResource("oq/source-name.txt");
        if (name == null || name.isBlank()) name = "main.oq";
        run(source, name.strip(), programArguments, Path.of("."));
    }

    public static void run(String source, String sourceName, String[] args, Path workingDirectory) {
        // Always emit UTF-8 so output is identical on every platform, including Windows
        // where the default console charset would mangle non-ASCII characters.
        java.io.PrintStream out = utf8(System.out);
        java.io.PrintStream err = utf8(System.err);
        List<String> programArgs = new ArrayList<>(List.of(args));
        // The first argument is the program's own name when launched via `java -jar x.jar`;
        // there is none here, so everything passed belongs to the program.
        BufferedReader in = new BufferedReader(new InputStreamReader(System.in, StandardCharsets.UTF_8));
        Interpreter interpreter = new Interpreter(out, err, in, programArgs,
                workingDirectory, new MethodResolverImpl());
        Stdlib.install(interpreter);
        try {
            Ast.Program program = Parser.parse(sourceName, source);
            program = Modules.resolveAgainst(program, workingDirectory);
            interpreter.run(program);
        } catch (Stdlib.ExitSignal exit) {
            System.exit(exit.code());
        } catch (OqError error) {
            Details.render(err, error, source, System.console() != null);
            System.exit(1);
        }
    }

    private static java.io.PrintStream utf8(java.io.OutputStream stream) {
        return new java.io.PrintStream(stream, true, StandardCharsets.UTF_8);
    }

    private static String readResource(String name) {
        try (InputStream in = EmbeddedMain.class.getClassLoader().getResourceAsStream(name)) {
            if (in == null) return null;
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (java.io.IOException e) {
            return null;
        }
    }
}
